"""홈 화면 문장 (오래된 고전에서 고른 문장, 한국어는 뜻을 살려 옮김)

- 오늘 기록이 없으면: 대표 문장 중 하나를 날짜마다 돌아가며
- 오늘 기록이 있으면: 그날 가장 큰 감정의 문장 (두 감정이 비슷하게 섞였으면 '섞인 날' 문장)
"""
import datetime as dt

DEFAULT = [
    ("춤추는 별을 낳으려면,\n자신 안에 혼돈을 품고 있어야 한다.", "니체, 『차라투스트라는 이렇게 말했다』"),
    ("같은 강물에\n두 번 발을 담글 수는 없다.", "헤라클레이토스"),
    ("자연은 언제나\n마음의 색을 입는다.", "에머슨, 『자연』"),
]

BY_EMOTION = {
    "기쁨": [("매일이 한 해 중\n가장 좋은 날임을 마음에 새겨라.", "에머슨"),
           ("행복한 삶을 위해\n필요한 것은 아주 적다.", "마르쿠스 아우렐리우스, 『명상록』")],
    "설렘": [("태양은\n아침별에 지나지 않는다.", "소로, 『월든』")],
    "평온": [("삶의 행복은\n생각의 결에 달려 있다.", "마르쿠스 아우렐리우스, 『명상록』")],
    "지침": [("천 리 길도\n한 걸음에서 시작된다.", "노자, 『도덕경』"),
           ("새는 알에서 나오려고 투쟁한다.\n알은 세계다.", "헤세, 『데미안』")],
    "슬픔": [("하늘 아래 모든 일에는\n때가 있다.", "『전도서』"),
           ("기쁨은\n가면을 벗은 슬픔이다.", "칼릴 지브란, 『예언자』")],
    "불안": [("우리는 현실보다\n상상 속에서 더 자주 괴로워한다.", "세네카, 『도덕 서한』")],
    "분노": [("사람을 괴롭히는 것은 일 자체가 아니라,\n그 일에 대한 생각이다.", "에픽테토스, 『엥케이리디온』")],
}
MIXED = ("마음에는\n이성이 알지 못하는 이유가 있다.", "파스칼, 『팡세』")


def pick(emotions: list[str], probs: list[float] | None, day: dt.date) -> tuple[str, str]:
    """오늘의 문장 고르기. probs가 없으면 대표 문장"""
    if not probs:
        return DEFAULT[day.toordinal() % len(DEFAULT)]
    order = sorted(range(len(probs)), key=lambda i: -probs[i])
    a, b = probs[order[0]], probs[order[1]]
    if b >= 0.25 and a - b < 0.1:          # 두 감정이 비슷하게 섞인 날
        return MIXED
    options = BY_EMOTION[emotions[order[0]]]
    return options[day.toordinal() % len(options)]
